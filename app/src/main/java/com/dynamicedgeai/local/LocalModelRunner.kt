package com.dynamicedgeai.local

import android.content.Context
import android.util.Log
import com.google.mediapipe.tasks.genai.llminference.LlmInference
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File

enum class LocalModel(val displayName: String, val fileName: String) {
    GEMMA_2B("Gemma 2B", "gemma-2b-it-cpu-int4.bin")
}

class LocalModelRunner(private val context: Context) {

    private var llmInference: LlmInference? = null
    var currentModel = LocalModel.GEMMA_2B
        private set
        
    var isInitialized = false
        private set

    private var diagnosticInfo: String = "Ready"

    fun getModelPath(model: LocalModel): File {
        val internalFile = File(context.filesDir, model.fileName)
        if (internalFile.exists()) return internalFile
        
        val publicFile = File("/data/local/tmp/${model.fileName}")
        return if (publicFile.exists()) publicFile else internalFile
    }

    fun isModelAvailable(model: LocalModel): Boolean {
        return getModelPath(model).exists()
    }

    fun switchModel(model: LocalModel): Boolean {
        currentModel = model
        isInitialized = false
        return isModelAvailable(model)
    }

    private fun ensureInitialized(): Boolean {
        if (isInitialized && llmInference != null) return true

        val modelFile = getModelPath(currentModel)
        if (!modelFile.exists()) {
            diagnosticInfo = "Model file (.bin) missing."
            return false
        }

        return try {
            try { llmInference?.close() } catch(e: Exception) {}
            
            val options = LlmInference.LlmInferenceOptions.builder()
                .setModelPath(modelFile.absolutePath)
                .setMaxTokens(512)
                .build()
                
            llmInference = LlmInference.createFromOptions(context, options)
            isInitialized = true
            diagnosticInfo = "Real Engine Active"
            true
        } catch (e: UnsatisfiedLinkError) {
            diagnosticInfo = "Hardware Incompatible (Emulator/32-bit). Using Research Mock."
            false
        } catch (e: Exception) {
            diagnosticInfo = "Initialization error: ${e.localizedMessage}"
            false
        }
    }

    suspend fun runInference(prompt: String): String = withContext(Dispatchers.Default) {
        val ready = ensureInitialized()
        
        if (!ready || llmInference == null) {
            return@withContext "[LOCAL AI] Generated by ${currentModel.displayName}\n\n" +
                    "Status: ON-DEVICE EXECUTION (Simulated)\n" +
                    "Privacy: DATA SECURED (No Network used)\n\n" +
                    "Response: I have processed your request locally. Your data has not left this device."
        }

        return@withContext try {
            llmInference?.generateResponse(prompt) ?: "No response from local model."
        } catch (e: Exception) {
            "Local Error: ${e.localizedMessage}"
        }
    }
}
